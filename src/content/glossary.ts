// The glossary key for a word as it appears in a sentence ("Mom's" → "mom"),
// or undefined when the word has no entry.
export function lookupWord(word: string): string | undefined {
  const w = word.toLowerCase().replace(/’/g, "'");
  if (w in GLOSSARY) return w;
  if (w.endsWith("'s") && w.slice(0, -2) in GLOSSARY) return w.slice(0, -2);
  return undefined;
}

export function displayWord(key: string): string {
  return GLOSSARY[key]?.display ?? key;
}

export type Token = { text: string; word: boolean };

// Splits a sentence into words and the spaces and punctuation between them.
export function tokenize(text: string): Token[] {
  return text
    .split(/([A-Za-z]+(?:['’][A-Za-z]+)?)/)
    .filter((t) => t !== '')
    .map((t) => ({ text: t, word: /^[A-Za-z]/.test(t) }));
}
